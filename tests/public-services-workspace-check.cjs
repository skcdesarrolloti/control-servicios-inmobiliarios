const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');

// Use the no-DB CLI-server harness. All saves are synthetic and send no messages.
(async () => {
  const base = process.env.SCM_SERVICES_QA_URL || 'http://127.0.0.1:9015';
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
  const errors = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/tests/assets/css/**', route => route.fulfill({ path: path.join(__dirname, '../public/assets/css', path.basename(new URL(route.request().url()).pathname)), contentType: 'text/css' }));
    await page.route('**/tests/assets/fonts/**', route => route.fulfill({ path: path.join(__dirname, '../public/assets/fonts', path.basename(new URL(route.request().url()).pathname)) }));
    await page.goto(base + '/tests/public-services-review-ui.php');
    const qaDir = path.join(__dirname, '../tmp/services-qa');
    fs.mkdirSync(qaDir, { recursive: true });
    const pendingRows = page.locator('[data-services-list="pending"] [data-services-contract-row]:visible');
    await page.waitForFunction(() => document.querySelector('[data-services-page-summary]').textContent.includes('de 24'));
    assert.equal(await pendingRows.count(), 10);
    await page.locator('#rsp_inmueble').fill('10156');
    const filterRequest = page.waitForRequest(request => (request.postData() || '').includes('scm_servicios_publicos_pendientes'));
    await page.locator('#rsp_form button[type="submit"]').click();
    assert((await filterRequest).postData().includes('10156'));
    const clearRequest = page.waitForRequest(request => (request.postData() || '').includes('scm_servicios_publicos_pendientes'));
    await page.locator('[data-pending-clear="rsp_"]').click();
    await clearRequest; assert.equal(await page.locator('#rsp_inmueble').inputValue(), '');
    await page.waitForFunction(() => !document.querySelector('#rsp_spinner').classList.contains('active'));
    await page.locator('[data-services-page-step="1"]').click();
    assert((await page.locator('[data-services-page-summary]').innerText()).includes('11 a 20'));
    await page.locator('[data-services-page-size]').selectOption('all');
    assert.equal(await pendingRows.count(), 24);
    await page.locator('[data-services-page-size]').selectOption('10');
    await page.locator('[data-services-quick="overdue"]').click();
    assert.equal(await page.locator('[data-services-quick="overdue"]').getAttribute('aria-pressed'), 'true');
    await page.locator('[data-services-quick="overdue"]').click();
    const downloadWait = page.waitForEvent('download');
    await page.locator('[data-services-export="pending"]').click();
    const download = await downloadWait; assert(download.suggestedFilename().endsWith('.csv'));
    await page.locator('[data-services-refresh]').click();
    await page.locator('[data-services-refresh]:not([disabled])').waitFor();
    assert.equal(await pendingRows.count(), 10);
    await page.screenshot({ path: path.join(qaDir, 'pending-tailwind.png'), fullPage: true });
    await page.locator('[data-services-tab="templates"]').click();
    assert(await page.locator('[data-services-header-pending]').first().isHidden());
    await page.locator('[data-services-template-form]').waitFor();
    assert(await page.locator('[data-services-section="pending"]').isHidden());
    await page.locator('[data-services-template-type]').selectOption('critico');
    await page.waitForFunction(() => document.querySelector('[name="body"]').value.includes('cuarenta y ocho (48)'));
    assert((await page.locator('[name="title"]').inputValue()).includes('90 días'));
    await page.locator('[name="title"]').fill('Requerimiento actualizado {{servicio}}');
    await page.locator('[name="body"]').evaluate(editor => { editor.focus(); editor.setSelectionRange(0,8); });
    await page.locator('[data-services-template-format="bold"]').click();
    assert((await page.locator('[name="body"]').inputValue()).startsWith('**Señor(a)**'));
    await page.locator('[name="body"]').focus();
    await page.locator('[name="body"]').evaluate(editor => editor.setSelectionRange(editor.value.length, editor.value.length));
    await page.locator('[data-services-variable="{{valor}}"]' ).click();
    assert((await page.locator('[name="body"]').inputValue()).includes('{{valor}}'));
    await page.locator('[data-services-template-preview]').click();
    await page.locator('[data-services-template-dialog][open]').waitFor();
    const frame = page.frameLocator('[data-services-template-dialog] iframe');
    await frame.locator('h1').waitFor();
    assert((await frame.locator('h1').innerText()).includes('Energía eléctrica'));
    assert((await frame.locator('body').innerText()).includes('$350.000 COP'));
    assert.equal(await frame.locator('strong').filter({ hasText: 'Señor(a)' }).count(), 1);
    await page.locator('[data-services-template-dialog] button').click();
    let declined = false;
    page.once('dialog', async dialog => { declined = true; await dialog.dismiss(); });
    await page.locator('[data-services-tab="history"]').click();
    assert(declined && await page.locator('[data-services-section="templates"]').isVisible());
    await page.locator('[data-services-template-form] button[type="submit"]').click();
    await page.waitForFunction(() => document.querySelector('#qa-result').textContent.includes('plantilla guardada'));
    assert.equal(await page.locator('[name="title"]').inputValue(), 'Requerimiento actualizado {{servicio}}');
    await page.screenshot({ path: path.join(qaDir, 'editor-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2));
    await page.screenshot({ path: path.join(qaDir, 'editor-mobile.png'), fullPage: true });
    await page.locator('[data-services-tab="history"]').click();
    await page.locator('[data-services-history-form]').waitFor();
    assert(await page.locator('[data-services-copy-url]').isVisible());
    await page.locator('[data-services-history-form] input[name="contrato"]').fill('149');
    await page.locator('[data-services-history-form] button[type="submit"]').click();
    await page.locator('[data-services-history-page="2"]').click();
    await page.locator('[data-services-history-order]').selectOption('asc');
    await page.waitForFunction(() => document.querySelector('[data-services-history-form] [name="order"]').value === 'asc');
    await page.setViewportSize({ width: 1440, height: 1050 });
    await page.screenshot({ path: path.join(qaDir, 'history-tailwind.png'), fullPage: true });
    const historyDownloadWait = page.waitForEvent('download');
    await page.locator('[data-services-export="history"]').click();
    assert((await historyDownloadWait).suggestedFilename().includes('pagina-actual'));
    await page.locator('[data-services-tab="pending"]').click();
    await page.locator('[data-services-list="pending"] [data-scm-open-public-services-review]').first().click();
    await page.locator('[data-public-services-review-form]').waitFor();
    const form = page.locator('[data-public-services-review-form]');
    await form.locator('[name="nic"]').fill('NIC-QA-cambio-pendiente');
    await form.locator('[data-public-services-date-adjustment] summary').click();
    await form.locator('[data-services-adjust-date]').fill('2026-01-31');
    await form.locator('[data-services-adjust-date]').dispatchEvent('change');
    assert((await form.locator('[data-services-adjust-preview]').innerText()).includes('30/04/2026'));
    await form.locator('[data-services-adjust-save]').click();
    assert(await form.locator('[data-services-adjust-error]').isVisible());
    await form.locator('[data-services-adjust-reason]').fill('Reorganización del atraso de revisiones');
    const adjustRequest = page.waitForRequest(request => (request.postData() || '').includes('adjust_date'));
    await form.locator('[data-services-adjust-save]').click();
    const sentAdjust = (await adjustRequest).postData();
    assert(sentAdjust.includes('2026-01-31') && !sentAdjust.includes('servicios_configurados'));
    await page.waitForFunction(() => document.querySelector('[data-public-services-review-form] [name="request_token"]').value === 'qa-refreshed-date-token');
    assert(await form.isVisible());
    assert.equal(await form.locator('[name="nic"]').inputValue(), 'NIC-QA-cambio-pendiente');
    assert(await form.locator('[data-public-service-card="agua"] .scm-public-service-fields').isHidden());
    await form.locator('[name="servicios_configurados[]"][value="agua"]').check();
    assert(await form.locator('[data-public-service-card="agua"] .scm-public-service-fields').isVisible());
    await form.locator('[name="servicios[]"][value="energia"]').uncheck();
    assert(await form.locator('[data-public-service-card="energia"] [data-public-service-account]').isEnabled());
    assert(await form.locator('[data-public-service-card="energia"] [data-public-service-status]').isHidden());
    await form.locator('[name="servicios[]"][value="energia"]').check();
    await page.screenshot({ path: path.join(qaDir, 'review-modal-tailwind.png'), fullPage: true });
    await page.locator('[role="dialog"]').last().screenshot({ path: path.join(qaDir, 'review-modal-component.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2));
    await page.screenshot({ path: path.join(qaDir, 'review-modal-mobile.png'), fullPage: true });
    page.once('dialog', dialog => dialog.accept());
    await page.locator('[data-public-services-review-close]').first().click();
    assert.equal(errors.length, 0, errors.join('\n'));
    console.log('PASS: subpestañas, editor crítico de 90 días, variables, vista previa, protección de borrador, guardado, historial, filtros, paginación, revisión modal y móvil sin desbordamiento. No DB writes or messages.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
