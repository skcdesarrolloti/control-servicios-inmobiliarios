const {chromium} = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  try {
    const page = await browser.newPage({viewport: {width: 1280, height: 1000}});
    const errors = [], submissions = [];
    let owner = 'employee-a', failSearch = false;
    page.on('pageerror', e => errors.push(e.message));
    await page.route('https://panel.test/api.php', async route => {
      const body = route.request().postDataBuffer().toString();
      const field = name => body.match(new RegExp(`name="${name}"\\r\\n\\r\\n([^\\r]*)`))?.[1];
      const action = field('action');
      if (action === 'scm_panel_case_search' && failSearch) { await route.fulfill({json: {success: false, data: {message: 'Conexión interrumpida'}}}); return; }
      let data;
      if (action === 'scm_panel_case_options') data = {draft_scope: owner, ai: {enabled: true}, themes: ['Reparaciones necesarias'], departments: ['Servicio al propietario'], theme_departments: {}, employees: [{employee_id: '9002', name: 'Consultor Ejemplo', cargo: 'Coordinación', email: 'qa@example.invalid'}], max_file_bytes: 10485760};
      if (action === 'scm_panel_case_search') data = {contracts: [{_ID: '801', contrato: '2000', inmueble: '204578', direccion: 'Calle de ejemplo', propietario: 'Propietario Ejemplo', arrendatario: 'Arrendatario Ejemplo', estado: 'Entregado'}]};
      if (action === 'scm_panel_case_create') { submissions.push({id: field('request_id'), body}); data = {ticket_id: 10999, message: 'Caso creado.'}; }
      assert(data, action);
      await route.fulfill({json: {success: true, data}});
    });
    await page.route('https://panel.test/', route => route.fulfill({contentType: 'text/html', body: '<html></html>'}));
    const mount = async () => {
      await page.goto('https://panel.test/');
      await page.setContent('<div data-scm-runtime="{&quot;ajaxUrl&quot;:&quot;https://panel.test/api.php&quot;,&quot;nonce&quot;:&quot;qa&quot;}"><button id="open">Nuevo caso</button></div>');
      await page.addStyleTag({content: fs.readFileSync(path.join(__dirname, '../public/assets/css/tailwind-admin.css'), 'utf8')});
      await page.addScriptTag({path: path.join(__dirname, '../public/assets/js/admin-case-create.js')});
      await page.evaluate(() => { document.querySelector('#open').onclick = () => window.dispatchEvent(new CustomEvent('scm:open-nuevo-ticket')); });
    };
    const open = async () => { await page.locator('#open').click(); await page.locator('[data-case-form]').waitFor(); await page.locator('[data-search]').waitFor(); await page.waitForFunction(() => !document.querySelector('[data-search]').disabled); };
    const close = async () => { await page.locator('[data-close]').click(); await page.locator('dialog').waitFor({state: 'detached'}); };
    const select = async () => { await page.locator('[data-search]').fill('2000'); await page.locator('[data-search-button]').click(); await page.locator('[data-results] button').click(); };
    const saved = async scope => page.evaluate(scope => new Promise((resolve, reject) => {
      const request = indexedDB.open('scm-panel-case-drafts', 1);
      request.onerror = reject;
      request.onsuccess = () => { const db = request.result; const get = db.transaction('drafts').objectStore('drafts').get(scope); get.onsuccess = () => { resolve(get.result ? {id: get.result.requestId, title: get.result.fields.asunto} : null); db.close(); }; };
    }), scope);
    await mount(); await open();
    assert(await page.locator('[data-contract-steps]').isHidden());
    await select();
    assert(await page.locator('[data-case-details]').isHidden(), 'after contract selection only the assistant question is shown');
    await page.locator('[data-assistant-choice=no]').click();
    assert(await page.locator('[data-ai-section]').isHidden(), 'manual choice hides assistant');
    await page.locator('[name=asunto]').fill('Borrador con evidencias');
    await page.locator('[name=descripcion]').fill('Descripción conservada después de un cierre accidental.');
    await page.locator('[name=tema_ayuda]').selectOption('Reparaciones necesarias');
    await page.locator('[name=departamento]').selectOption('Servicio al propietario');
    await page.locator('[name=id_empleado]').selectOption('9002');
    await page.locator('[name="notify_roles[]"][value=propietario]').check();
    await page.locator('[name=has_attachments]').selectOption('Si');
    const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aM1kAAAAASUVORK5CYII=', 'base64');
    await page.locator('[name="imagenes[]"]').setInputFiles({name: 'evidencia.png', mimeType: 'image/png', buffer: png});
    await page.locator('[name="archivos[]"]').setInputFiles({name: 'soporte.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4 test')});
    assert(await page.locator('[name="imagenes[]"]').isHidden(), 'native file picker field is hidden behind styled buttons');
    assert(await page.locator('[data-pick-media=images]').isVisible());
    await page.locator('[data-assistant-choice=yes]').click();
    assert(await page.locator('[data-ai-section]').isVisible());
    assert(!(await page.locator('[data-ai-section]').innerText()).includes('Completar con IA'));
    await page.locator('[data-ai-text]').fill('Contenido de correo para el asistente.');
    await page.locator('[data-ai-images]').setInputFiles({name: 'correo.png', mimeType: 'image/png', buffer: png});
    await page.mouse.click(2, 2);
    assert(await page.locator('dialog').isVisible(), 'backdrop click does not dismiss case creation');
    await page.keyboard.press('Escape');
    assert(await page.locator('dialog').isVisible(), 'Escape does not dismiss case creation');
    const chooserPromise = page.waitForEvent('filechooser');
    await page.locator('[data-pick-media=assistant]').click();
    await (await chooserPromise).setFiles([]);
    assert(await page.locator('dialog').isVisible(), 'cancelled media selection leaves case creation open');
    await close();
    const firstSaved = await saved(owner);
    assert(firstSaved?.id && firstSaved.title === 'Borrador con evidencias');
    await open();
    assert.equal(await page.locator('[name=asunto]').inputValue(), firstSaved.title);
    assert.equal(await page.locator('[data-pasted-images] img').count(), 1, 'uploaded image recovers with its actual file and preview');
    assert.equal(await page.locator('[name="archivos[]"]').evaluate(input => input.files[0].name), 'soporte.pdf');
    assert.equal(await page.locator('[data-ai-previews] img').count(), 1, 'private source capture also recovers');
    assert.equal(await page.locator('[data-ai-text]').inputValue(), 'Contenido de correo para el asistente.');
    assert(await page.locator('[name="notify_roles[]"][value=propietario]').isChecked());
    assert.equal(await page.locator('[data-assistant-choice=yes]').getAttribute('aria-pressed'), 'true');
    await close(); await mount(); await open();
    assert.equal(await page.locator('[name=asunto]').inputValue(), firstSaved.title, 'draft survives page reload');
    await close(); failSearch = true; await open();
    assert.equal(await page.locator('[name=asunto]').inputValue(), firstSaved.title, 'contract lookup failure preserves recovered text');
    assert.equal(await page.locator('[data-pasted-images] img').count(), 1, 'contract lookup failure preserves recovered files');
    assert(await page.locator('[data-contract-steps]').isHidden(), 'failed contract revalidation requires a fresh selection');
    failSearch = false; await select(); await page.locator('[data-assistant-choice=yes]').click();
    await close(); owner = 'employee-b'; await open();
    assert(await page.locator('[data-contract-steps]').isHidden(), 'a different employee cannot recover another employee draft');
    await select(); await page.locator('[data-assistant-choice=no]').click(); await page.locator('[name=asunto]').fill('Borrador B'); await close();
    owner = 'employee-a'; await open();
    assert.equal(await page.locator('[name=asunto]').inputValue(), firstSaved.title);
    fs.mkdirSync(path.join(__dirname, '../output/panel-case-draft'), {recursive: true});
    await page.locator('[data-ai-section]').scrollIntoViewIfNeeded();
    await page.screenshot({path: path.join(__dirname, '../output/panel-case-draft/desktop.png')});
    await page.setViewportSize({width: 390, height: 844});
    assert(await page.evaluate(() => document.querySelector('dialog').scrollWidth <= document.querySelector('dialog').clientWidth));
    await page.locator('[data-pick-media=images]').scrollIntoViewIfNeeded();
    await page.screenshot({path: path.join(__dirname, '../output/panel-case-draft/mobile.png')});
    await page.locator('[type=submit]').click();
    await page.locator('[data-done]').waitFor();
    assert.equal(submissions[0].id, firstSaved.id, 'recovered request ID prevents duplicate case creation');
    assert(submissions[0].body.includes('evidencia.png') && submissions[0].body.includes('soporte.pdf'));
    assert(!submissions[0].body.includes('correo.png'), 'private source screenshot remains excluded from case files');
    assert.equal(await saved('employee-a'), null, 'successful creation removes draft');
    await page.locator('[data-done]').click(); await page.locator('dialog').waitFor({state: 'detached'});
    owner = 'employee-b'; await open();
    await page.locator('[data-discard-draft]').click();
    assert.equal(await page.locator('[name=asunto]').inputValue(), 'Borrador B', 'discard requires explicit confirmation');
    await page.locator('[data-confirm-discard]').click();
    await page.waitForFunction(() => document.querySelector('[data-draft-status]').textContent.includes('descartado'));
    assert.equal(await saved(owner), null);
    assert(await page.locator('[data-contract-steps]').isHidden());
    await select(); await page.locator('[data-assistant-choice=no]').click(); await page.locator('[name=asunto]').fill('No perder si falla el almacenamiento');
    await page.evaluate(() => { const original = IDBObjectStore.prototype.put; window.restoreDraftPut = () => { IDBObjectStore.prototype.put = original; }; IDBObjectStore.prototype.put = () => { throw new DOMException('Storage full', 'QuotaExceededError'); }; });
    await page.locator('[data-close]').click();
    await page.waitForFunction(() => document.querySelector('[data-draft-status]').textContent.includes('No se pudo autoguardar'));
    assert(await page.locator('dialog').isVisible(), 'storage failure prevents explicit close from losing the draft');
    assert.equal(await page.locator('[name=asunto]').inputValue(), 'No perder si falla el almacenamiento');
    await page.evaluate(() => window.restoreDraftPut()); await close();
    assert.deepEqual(errors, []);
    console.log('PASS: assistant choice, styled media, dismissal protection, file/text recovery, reload, employee isolation, idempotency and confirmed draft removal');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
